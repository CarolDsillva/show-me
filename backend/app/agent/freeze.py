"""Freeze an action trail into a Playwright script, by code rather than by the model.

The script runs only in the sandbox. Every model-chosen value is rendered with repr(), so
it stays a string literal. No model text reaches the script as code or as a comment.
"""

from __future__ import annotations

import hashlib

from app.agent.actions import Expectation, NextAction

SYMPTOM_EXIT = 42
STEP_FAILED_EXIT = 3

HEADER = '''"""Show Me frozen reproduction. Generated by code, and hashed before its first replay.

Exit 42: every step worked and the expected behavior didn't happen, so the symptom is present.
Exit 3: a step failed, which counts as not reproduced.
Exit 0: the expected behavior happened.
"""
import os
import re
import sys

from playwright.sync_api import expect, sync_playwright

BASE = "http://127.0.0.1:9090"


def settle(page):
    try:
        page.wait_for_load_state("load", timeout=3000)
    except Exception:
        pass
    page.wait_for_timeout(400)


def steps(page):
    page.goto(f"{BASE}/login/", wait_until="load", timeout=60000)
    page.fill('input[name="username"]', os.environ["RF_USER"])
    page.fill('input[name="password"]', os.environ["RF_PASSWORD"])
    page.press('input[name="password"]', "Enter")
    page.wait_for_url("**/bookmarks**", timeout=60000)
    settle(page)
'''

FOOTER = '''

with sync_playwright() as playwright:
    browser = playwright.chromium.launch(headless=True, args=["--no-sandbox", "--disable-gpu"])
    context = browser.new_context(viewport={"width": 1280, "height": 800})
    context.route("**/*", lambda route: route.continue_() if route.request.url.startswith(BASE + "/") else route.abort())
    page = context.new_page()
    code = 0
    try:
        steps(page)
    except Exception as error:
        print("STEP FAILED:", type(error).__name__, str(error)[:500], flush=True)
        code = 3
    if code == 0:
        try:
            check(page)
            print("EXPECTED BEHAVIOR HAPPENED", flush=True)
        except AssertionError as error:
            print("SYMPTOM OBSERVED:", str(error)[:500], flush=True)
            code = 42
    print("FINAL URL:", page.url, flush=True)
    try:
        page.screenshot(path="/tmp/final.png", type="png")
    except Exception:
        pass
    browser.close()
sys.exit(code)
'''


def render_step(step: NextAction) -> list[str]:
    selector, value = repr(step.selector), repr(step.value or "")
    match step.action:
        case "goto":
            lines = [f'page.goto(BASE + {step.path!r}, wait_until="load", timeout=8000)']
        case "click":
            lines = [f"page.click({selector}, timeout=8000)"]
        case "fill":
            lines = [f"page.fill({selector}, {value}, timeout=8000)"]
        case "press":
            lines = [f"page.press({selector}, {value}, timeout=8000)"]
        case "select":
            lines = [f"page.select_option({selector}, {value}, timeout=8000)"]
        case "wait_for":
            lines = [f"page.wait_for_selector({selector}, timeout=8000)"]
        case _:
            raise ValueError(f"Not replayable: {step.action}")
    return [*lines, "settle(page)"]


def render_check(expectation: Expectation) -> str:
    value = repr(expectation.value)
    match expectation.kind:
        case "url_contains":
            return f"expect(page).to_have_url(re.compile(re.escape({value})), timeout=8000)"
        case "text_visible":
            return f"expect(page.get_by_text({value}).first).to_be_visible(timeout=8000)"
        case "text_not_visible":
            return f"expect(page.get_by_text({value})).to_have_count(0, timeout=8000)"
        case "selector_visible":
            return f"expect(page.locator({value}).first).to_be_visible(timeout=8000)"
        case "selector_not_visible":
            return f"expect(page.locator({value})).to_have_count(0, timeout=8000)"
    raise ValueError(f"Unknown expectation: {expectation.kind}")


def simplify_trail(trail: list[NextAction]) -> list[NextAction]:
    """Drop steps with no lasting effect, so the script reads as the shortest route found.

    A goto straight before another goto does nothing, a repeated run of identical steps adds
    nothing, and plain link clicks before the last goto only wander. Anything that fills in or
    submits data is kept, because it may matter. The replays still decide whether the shorter
    script shows the symptom.
    """
    def key(step: NextAction) -> tuple:
        return (step.action, step.path, step.selector, step.value)

    steps = [step for i, step in enumerate(trail) if not (
        step.action == "goto" and i + 1 < len(trail) and trail[i + 1].action == "goto"
    )]
    changed = True
    while changed:
        changed = False
        for size in range(1, len(steps) // 2 + 1):
            for start in range(len(steps) - 2 * size + 1):
                first = [key(step) for step in steps[start:start + size]]
                second = [key(step) for step in steps[start + size:start + 2 * size]]
                if first == second:
                    del steps[start + size:start + 2 * size]
                    changed = True
                    break
            if changed:
                break
        goto_pairs = [i for i in range(len(steps) - 1) if steps[i].action == "goto" and steps[i + 1].action == "goto"]
        if goto_pairs:
            del steps[goto_pairs[0]]
            changed = True
    last_goto = max((i for i, step in enumerate(steps) if step.action == "goto"), default=0)
    before = steps[:last_goto]
    if all(step.action == "goto" or (step.action == "click" and (step.selector or "").startswith("a[href")) for step in before):
        steps = steps[last_goto:]
    return steps


def freeze(trail: list[NextAction], expectation: Expectation) -> tuple[str, str]:
    """Return the script and its SHA-256."""
    lines = [HEADER.rstrip("\n")]
    for step in trail:
        lines.extend(f"    {line}" for line in render_step(step))
    lines.append("")
    lines.append("")
    lines.append("def check(page):")
    lines.append(f"    {render_check(expectation)}")
    script = "\n".join(lines) + "\n" + FOOTER
    return script, hashlib.sha256(script.encode()).hexdigest()
